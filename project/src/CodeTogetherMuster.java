public class CodeTogetherMuster {
    public static void main(String[] args) {
        
        int momentanerBurger = 4;
        int letzterBurger = 8;

        while (momentanerBurger <= letzterBurger) {
            System.out.println("Schmeiß Burger Nr." + momentanerBurger + " auf den Grill");
            momentanerBurger++;
        }
    }
}
